TEMPLATES_BY_TYPE = {t.event_type: t for t in EVENT_TEMPLATES}


# ==================================================================
# Event and Episode
# ==================================================================

@dataclass
class Event:
    episode: int
    index: int
    event_type: str
    description: str
    is_bid: bool
    child_utterance: str
    availability: str          # "free" | "occupied" | "depleted"
    availability_context: str  # the sentence given to the mother

    def mother_context(self) -> str:
        """The situational line appended to the mother's system prompt."""
        return self.availability_context


@dataclass
class Episode:
    index: int
    events: List[Event] = field(default_factory=list)


# ==================================================================
# Generator
# ==================================================================

class EventGenerator:
    """Generates episodes of attachment-relevant events.

    reliability
        Probability that the mother is environmentally FREE when a bid
        arrives. This is the independent variable. High reliability
        means she is usually available to respond; low reliability
        means bids usually land while she is occupied or depleted.
        Her disposition is untouched -- only her circumstances.

    Note that reliability applies to BIDS specifically. Mundane events
    get an availability draw too, but nothing hinges on it.
    """

    def __init__(self, reliability: float = 0.7, seed: Optional[int] = None):
        if not 0.0 <= reliability <= 1.0:
            raise ValueError("reliability must be between 0 and 1")
        self.reliability = reliability
        self.rng = random.Random(seed)

    def _draw_availability(self) -> str:
        if self.rng.random() < self.reliability:
            return "free"
        # When not free, split the remainder between the two ways of
        # being unavailable.
        return self.rng.choice(["occupied", "depleted"])

    def _make_event(self, episode_idx: int, event_idx: int,
                    template: EventTemplate,
                    used_utterances: set) -> Event:
        availability = self._draw_availability()

        # Don't repeat a literal utterance within an episode.
        options = [u for u in template.child_utterances
                   if u not in used_utterances]
        if not options:
            options = template.child_utterances
        utterance = self.rng.choice(options)
        used_utterances.add(utterance)

        return Event(
            episode=episode_idx,
            index=event_idx,
            event_type=template.event_type,
            description=template.description,
            is_bid=template.is_bid,
            child_utterance=utterance,
            availability=availability,
            availability_context=self.rng.choice(AVAILABILITY[availability]),
        )

    def generate_episode(self, episode_idx: int,
                         n_events: int = 6) -> Episode:
        """One episode, roughly a day.

        Structure, deliberately not uniform random:
          - Separation and reunion are paired when they appear, in that
            order, since a reunion only means something after a leaving.
          - At least one mundane event, so the relationship isn't made
            purely of demands.
          - The rest drawn from the bid types.
        """
        episode = Episode(index=episode_idx)
        slots: List[EventTemplate] = []

        # Roughly a third of episodes contain a separation/reunion pair.
        if self.rng.random() < 0.35 and n_events >= 4:
            slots.append(TEMPLATES_BY_TYPE["separation"])
            slots.append(TEMPLATES_BY_TYPE["reunion"])

        # One mundane exchange.
        slots.append(TEMPLATES_BY_TYPE["mundane"])

        # Fill the rest with bid events, no immediate repeats.
        bid_types = [t for t in EVENT_TEMPLATES
                     if t.is_bid and t.event_type not in
                     ("separation", "reunion")]
        while len(slots) < n_events:
            choice = self.rng.choice(bid_types)
            if slots and slots[-1].event_type == choice.event_type:
                continue
            slots.append(choice)

        # Keep separation before reunion; otherwise shuffle.
        sep_reunion = [s for s in slots
                       if s.event_type in ("separation", "reunion")]
        others = [s for s in slots
                  if s.event_type not in ("separation", "reunion")]
        self.rng.shuffle(others)

        if sep_reunion:
            # Drop the pair somewhere in the middle, in order.
            cut = self.rng.randint(1, max(1, len(others) - 1))
            ordered = others[:cut] + sep_reunion + others[cut:]
        else:
            ordered = others

        ordered = self._separate_adjacent_duplicates(ordered)

        used_utterances: set = set()
        for i, template in enumerate(ordered):
            episode.events.append(
                self._make_event(episode_idx, i, template, used_utterances)
            )

        return episode

    @staticmethod
    def _separate_adjacent_duplicates(
        templates: List[EventTemplate],
    ) -> List[EventTemplate]:
        """Break up same-type neighbours introduced by the shuffle.

        The no-repeat check during slot selection happens before
        shuffling, so shuffling can put two events of the same type
        next to each other again. This swaps a duplicate forward with
        the next non-matching element. Separation/reunion pairs are
        never same-type, so their order is unaffected.
        """
        result = list(templates)
        for i in range(1, len(result)):
            if result[i].event_type != result[i - 1].event_type:
                continue
            for j in range(i + 1, len(result)):
                if (result[j].event_type != result[i - 1].event_type
                        and (j + 1 >= len(result)
                             or result[j + 1].event_type
                             != result[i].event_type)):
                    result[i], result[j] = result[j], result[i]
                    break
        return result

    def generate_run(self, n_episodes: int = 10,
                     events_per_episode: int = 6) -> List[Episode]:
        return [self.generate_episode(i, events_per_episode)
                for i in range(n_episodes)]


# ==================================================================
# Serialization + summary
# ==================================================================

def save_run(episodes: List[Episode], path: str) -> None:
    with open(path, "w") as f:
        for ep in episodes:
            for ev in ep.events:
                f.write(json.dumps(asdict(ev)) + "\n")


def summarize(episodes: List[Episode]) -> None:
    from collections import Counter

    all_events = [ev for ep in episodes for ev in ep.events]
    bids = [ev for ev in all_events if ev.is_bid]
    free_bids = [ev for ev in bids if ev.availability == "free"]

    print(f"episodes:        {len(episodes)}")
    print(f"events total:    {len(all_events)}")
    print(f"bids:            {len(bids)}")
    print(f"bids met free:   {len(free_bids)} "
          f"({len(free_bids) / len(bids):.0%} of bids)")
    print()

    print("event type distribution:")
    for etype, n in Counter(ev.event_type for ev in all_events).most_common():
        print(f"    {etype:<18} {n}")
    print()

    print("availability distribution:")
    for avail, n in Counter(ev.availability for ev in all_events).most_common():
        print(f"    {avail:<18} {n}")


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--episodes", type=int, default=10)
    ap.add_argument("--events", type=int, default=6)
    ap.add_argument("--prefix", default="events",
                    help="output filename prefix")
    ap.add_argument("--high", type=float, default=0.9)
    ap.add_argument("--low", type=float, default=0.15)
    ap.add_argument("--low-seed-offset", type=int, default=0,
                    help="add this to the seed for the LOW arm only. "
                         "Normally 0, so both arms see the same event "
                         "stream and differ only in reliability (a "
                         "matched-pairs design). For a NULL CONTROL where "
                         "both reliabilities are equal, this must be "
                         "nonzero -- otherwise both arms draw identical "
                         "events with identical sampling and the "
                         "difference is trivially zero, which tests "
                         "nothing.")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    for reliability, label, offset in [
            (args.high, "high_reliability", 0),
            (args.low, "low_reliability", args.low_seed_offset)]:
        gen = EventGenerator(reliability=reliability,
                             seed=args.seed + offset)
        episodes = gen.generate_run(n_episodes=args.episodes,
                                    events_per_episode=args.events)
        out = f"{args.prefix}_{label}.jsonl"
        save_run(episodes, out)
        if not args.quiet:
            print("=" * 62)
            print(f"CONDITION: {label} "
                  f"(reliability={reliability}, seed={args.seed})")
            print("=" * 62)
            summarize(episodes)
            print()
        print(f"wrote {out}")


if __name__ == "__main__":
    main()